import { test, expect, signIn, visit, scope, unitInput, propertyInput, type Role } from './fixtures.ts'

test('property → unit → availability → dashboard → archive workflow', async ({ page, qa }) => {
  const account = await qa.account()
  await signIn(page, account)
  await expect(page.getByLabel('Total properties: 0')).toBeVisible()
  await page.getByRole('link', { name: 'Add property', exact: true }).click()
  await page.getByLabel('Property name').fill('Playwright property')
  await page.getByLabel('Address line 1', { exact: true }).fill('QA street')
  await page.getByLabel('City').fill('Kabul')
  await page.getByLabel('Country code').fill('AF')
  await page.getByRole('button', { name: 'Save property' }).click()
  await expect(page.getByRole('heading', { name: 'Playwright property' })).toBeVisible()
  const propertyPath = new URL(page.url()).pathname
  await page.getByRole('link', { name: 'Edit property', exact: true }).click()
  await page.getByLabel('Property name').fill('Edited property')
  await page.getByRole('button', { name: 'Save property' }).click()
  await expect(page.getByRole('heading', { name: 'Edited property' })).toBeVisible()
  await page.getByRole('link', { name: 'Manage Units' }).click()
  await page.getByRole('link', { name: 'Create unit', exact: true }).click()
  await page.getByLabel('Unit number *', { exact: true }).fill('PW-101')
  await page.getByRole('button', { name: 'Save unit' }).click()
  await expect(page.getByRole('heading', { name: 'PW-101' })).toBeVisible()
  const unitPath = new URL(page.url()).pathname
  await page.getByRole('link', { name: 'Edit unit', exact: true }).click()
  await page.getByLabel('Unit number *', { exact: true }).fill('PW-102')
  await page.getByRole('button', { name: 'Save unit' }).click()
  await expect(page.getByRole('heading', { name: 'PW-102' })).toBeVisible()
  for (const status of ['UNAVAILABLE','AVAILABLE']) {
    await page.getByRole('button', { name: `Mark ${status}` }).click()
    await page.getByRole('button', { name: 'Change availability', exact: true }).click()
    await expect(page.getByText(`Availability: ${status}`, { exact: true })).toBeVisible()
    await visit(page, '/dashboard')
    await expect(page.getByLabel('Total properties: 1')).toBeVisible()
    await expect(page.getByLabel('Total units: 1')).toBeVisible()
    await expect(page.getByLabel(`${status === 'AVAILABLE' ? 'Available' : 'Unavailable'} units: 1`)).toBeVisible()
    await visit(page, unitPath)
  }
  await expect(page.getByRole('button', { name: /Mark OCCUPIED/ })).toHaveCount(0)
  await visit(page, propertyPath)
  await page.getByRole('button', { name: 'Archive property', exact: true }).click()
  await page.getByRole('button', { name: 'Archive', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'This property is archived' })).toBeVisible()
  await visit(page, unitPath)
  await expect(page.getByText(/This property is archived/)).toBeVisible()
  await expect(page.getByRole('link', { name: 'Edit unit', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Mark / })).toHaveCount(0)
  await visit(page, '/dashboard')
  await expect(page.getByLabel('Archived properties: 1')).toBeVisible()
  await expect(page.getByLabel('Total units: 1')).toBeVisible()
})

for (const role of ['OWNER','ADMIN','MANAGER','STAFF'] as Role[]) test(`${role}: real UI and independent backend authorization`, async ({ page, qa }) => {
  const account = await qa.account(role)
  const { propertyId, unitId } = await qa.seed(account)
  const { client } = await qa.loginAPI(account)
  await signIn(page, account)
  const manages = role !== 'STAFF'
  await expect(page.getByRole('link', { name: 'Add property', exact: true })).toHaveCount(manages ? 1 : 0)
  await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Settings' })).toHaveCount(1)
  await visit(page, `/properties/${propertyId}`)
  await expect(page.getByRole('heading', { name: 'QA property' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Edit property', exact: true })).toHaveCount(manages ? 1 : 0)
  await expect(page.getByRole('button', { name: 'Archive property', exact: true })).toHaveCount(manages ? 1 : 0)
  await page.getByRole('link', { name: 'Manage Units' }).click()
  await expect(page.getByRole('link', { name: 'QA-101', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Create unit', exact: true })).toHaveCount(manages ? 1 : 0)
  await page.getByRole('link', { name: 'QA-101', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Edit unit', exact: true })).toHaveCount(manages ? 1 : 0)
  await expect(page.getByRole('button', { name: 'Mark UNAVAILABLE' })).toHaveCount(manages ? 1 : 0)
  const base = `${scope(account)}/properties/${propertyId}`
  expect((await client.post(`${scope(account)}/properties`, { data: propertyInput })).status()).toBe(manages ? 201 : 403)
  expect((await client.patch(base, { data: { name: 'Role updated' } })).status()).toBe(manages ? 200 : 403)
  expect((await client.post(`${base}/units`, { data: { ...unitInput, unitNumber: 'ROLE-2' } })).status()).toBe(manages ? 201 : 403)
  expect((await client.patch(`${base}/units/${unitId}`, { data: { floorNumber: 2 } })).status()).toBe(manages ? 200 : 403)
  expect((await client.patch(`${base}/units/${unitId}/availability`, { data: { availabilityStatus: 'UNAVAILABLE' } })).status()).toBe(manages ? 200 : 403)
  expect((await client.patch(`${base}/archive`)).status()).toBe(manages ? 200 : 403)
  if (!manages) {
    await visit(page, `${base.replace(scope(account), '')}/units/new`)
    await expect(page.getByRole('heading', { name: /Access|Forbidden/i })).toBeVisible()
  }
})

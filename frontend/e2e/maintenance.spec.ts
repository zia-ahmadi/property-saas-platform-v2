import { test, expect, signIn, sql, uuid, visit } from './fixtures.ts'

test('staff logs a unit repair from a property and resolves it on mobile', async ({ page, qa }) => {
  const staff = await qa.account('STAFF')
  const { propertyId, unitId } = await qa.seed(staff)
  sql(`INSERT INTO properties(organization_id,name,property_type,address_line1,city,country_code,status)
       SELECT '${uuid(staff.organizationId)}', 'Archived ' || n, 'house', 'Test street', 'Kabul', 'AF', 'archived'
       FROM generate_series(1, 26) AS n;`)
  await signIn(page, staff)
  await page.getByRole('link', { name: 'Maintenance', exact: true }).click()
  await page.getByRole('link', { name: 'New request' }).first().click()
  const property = page.getByRole('combobox', { name: 'Property', exact: true })
  await expect(property.getByRole('option', { name: 'QA property' })).toBeAttached()
  await page.getByRole('searchbox', { name: 'Find a property' }).fill('Archived')
  await expect(page.getByText('No active properties match your search.')).toBeVisible()
  await page.getByRole('searchbox', { name: 'Find a property' }).fill('qa PRO')
  await property.selectOption({ label: 'QA property' })
  await expect(property).toHaveValue(propertyId)
  await visit(page, `/properties/${propertyId}`)
  await page.getByRole('link', { name: 'View maintenance requests' }).click()
  await expect(page.getByRole('heading', { name: 'Requests for QA property' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'No matching requests' })).toBeVisible()

  await page.getByRole('link', { name: 'New request' }).click()
  await expect(page.getByRole('combobox', { name: 'Property', exact: true })).toHaveValue(propertyId)
  await page.getByRole('combobox', { name: 'Unit', exact: true }).selectOption(unitId)
  await page.getByLabel('Title', { exact: true }).fill('Kitchen sink leak')
  await page.getByLabel('Description', { exact: true }).fill('Leak under the kitchen sink.')
  await page.getByRole('combobox', { name: 'Category', exact: true }).selectOption('PLUMBING')
  await page.getByRole('combobox', { name: 'Priority', exact: true }).selectOption('URGENT')
  await page.getByLabel('Assigned to').fill('Sam')
  await page.getByLabel('Due date').fill('2024-01-15')
  await page.getByRole('button', { name: 'Create request' }).click()
  await expect(page.getByRole('heading', { name: 'Kitchen sink leak' })).toBeVisible()
  await page.getByRole('link', { name: 'Back to maintenance' }).click()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Search requests').fill('kitchen')
  await expect(page).toHaveURL(/search=kitchen/)
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('OPEN')
  await expect(page).toHaveURL(/search=kitchen.*status=OPEN/)
  const item = page.getByRole('link', { name: /Kitchen sink leak/ })
  await expect(page.getByRole('row').filter({ has: item })).toContainText('Overdue')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await item.click()
  await expect(page.getByRole('heading', { name: 'Kitchen sink leak' })).toBeVisible()

  await page.getByRole('article').getByRole('combobox', { name: 'Status', exact: true }).selectOption('RESOLVED')
  await page.getByLabel('Resolution notes').fill('Replaced the worn seal.')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByText('Maintenance request updated')).toBeVisible()
  await page.getByRole('link', { name: 'Back to maintenance' }).click()
  await expect(page.getByRole('heading', { name: 'No matching requests' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('RESOLVED')
  await expect(page.getByRole('row').filter({ has: item })).toContainText('Resolved')
  await expect(page.getByRole('row').filter({ has: item })).not.toContainText('Overdue')
})
